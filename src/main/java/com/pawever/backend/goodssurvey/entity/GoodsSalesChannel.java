package com.pawever.backend.goodssurvey.entity;

/**
 * 굿즈를 파는 통로.
 *
 * 통로마다 값과 정원이 다르다. 온라인은 정가 29,900원에 100자리, 플리마켓은
 * 현장 한정가 11,900원에 70자리다. 같은 물건이지만 같은 조건이 아니라서,
 * 어느 통로로 들어온 주문인지가 값을 정한다.
 *
 * 통로는 모집(캠페인)에 붙는다. 설정이 어느 캠페인을 열지 고르고, 캠페인이
 * 자기 통로를 들고 있다. 설정을 지워 통로를 닫아도 이미 그 캠페인에 붙은
 * 주문은 자기가 동의한 값 그대로 계산된다.
 */
public enum GoodsSalesChannel {

    /** 상시 온라인 판매. */
    ONLINE,

    /** 과기대 플리마켓 현장 판매. 행사가 끝나면 설정에서 지워 닫는다. */
    FLEA
}
