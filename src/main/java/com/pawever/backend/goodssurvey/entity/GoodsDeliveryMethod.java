package com.pawever.backend.goodssurvey.entity;

/**
 * 만든 물건을 건네는 방법.
 *
 * 택배는 주소를 받고 배송비를 더한다. 현장 수령은 둘 다 없다 — 받는 사람이
 * 그 자리에 오므로 주소를 물을 이유가 없고, 부치지 않으니 배송비도 없다.
 *
 * 현장 수령은 행사장이 있는 경로에서만 고를 수 있다. 상시 온라인 판매에서
 * 열어 두면 부칠 곳 없는 주문이 들어온다.
 *
 * 근거: [피그마 0uW99BqaTJKUVlowzQswli / 8-2 Rending Page]
 *       5472:1482 "방문수령 외 택배 시 배송비 3,000원 별도"
 *       5472:1755 "선착순 70명 예약하고, 과기대에서 수령하기"
 */
public enum GoodsDeliveryMethod {

    /** 택배로 부친다. 주소가 있어야 하고 배송비가 붙는다. */
    SHIPPING,

    /** 행사장에서 직접 건넨다. 주소를 받지 않고 배송비도 없다. */
    PICKUP
}
