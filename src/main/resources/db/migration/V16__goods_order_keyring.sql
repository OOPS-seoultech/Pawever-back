-- 키링 부자재를 주문에 적는다.
--
-- 현장에서 "2,000원 추가하면 키링으로 만들어 준다"를 받기로 했다. 제작팀이
-- 고리를 달아야 하므로 어느 주문이 키링인지 알아야 하고, 값이 달라지므로
-- 얼마를 부자재값으로 받았는지도 알아야 한다.
--
-- 값을 따로 적는 이유는 배송비와 같다. 청구액에 이미 들어가 있지만 설정값이
-- 바뀌어도 이미 받은 주문의 금액은 그대로여야 하고, 나중에 얼마가 무엇이었는지
-- 가릴 근거가 있어야 한다.
--
-- 붙였는지를 값과 따로 두는 이유는, 언젠가 부자재를 그냥 달아 주는 날이
-- 오면 값은 0 인데 고리는 달아야 하기 때문이다. 값으로만 판단하면 그 주문은
-- 키링이 아닌 것으로 읽힌다.
--
-- 기본값: 이미 들어온 주문은 키링이 아니다. 값을 채워 넣으면 받지도 않은
-- 돈을 받은 것으로 적게 되고, 달지도 않을 고리를 달 것으로 적게 된다.
ALTER TABLE `goods_survey_fulfillments`
    ADD COLUMN `keyring_added` BOOLEAN NOT NULL DEFAULT FALSE AFTER `shipping_fee_krw`,
    ADD COLUMN `keyring_fee_krw` INT NOT NULL DEFAULT 0 AFTER `keyring_added`;
